const CATEGORY_NAMES = Object.keys(CATEGORIES);
const ALL_CATEGORY = "सर्व श्रेणी";

function pickPair(category, usedKeys) {
  let pool;
  if (category === ALL_CATEGORY || !CATEGORIES[category]) {
    pool = [];
    for (const c of CATEGORY_NAMES) for (const p of CATEGORIES[c]) pool.push({ c, p });
  } else {
    pool = CATEGORIES[category].map((p) => ({ c: category, p }));
  }
  let fresh = pool.filter((x) => !usedKeys.has(x.p[0] + "|" + x.p[1]));
  if (fresh.length === 0) {
    usedKeys.clear();
    fresh = pool;
  }
  const choice = fresh[Math.floor(Math.random() * fresh.length)];
  usedKeys.add(choice.p[0] + "|" + choice.p[1]);
  // जोडीतील कोणता शब्द सामान्य व कोणता इम्पोस्टरचा हे यादृच्छिक ठेवतो
  const flip = Math.random() < 0.5;
  return {
    category: choice.c,
    crewWord: flip ? choice.p[1] : choice.p[0],
    imposterWord: flip ? choice.p[0] : choice.p[1],
  };
}

function stats() {
  const words = new Set();
  let pairs = 0;
  for (const c of CATEGORY_NAMES) for (const p of CATEGORIES[c]) { pairs++; words.add(p[0]); words.add(p[1]); }
  return { categories: CATEGORY_NAMES.length, pairs, uniqueWords: words.size };
}

module.exports = { CATEGORIES, CATEGORY_NAMES, ALL_CATEGORY, pickPair, stats };
